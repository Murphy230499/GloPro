for lang, pairs in translations.items():
    # Looking for exactly "lang: {" with trailing spaces possibly
    pattern = rf'(\b{lang}\b\s*:\s*{{)'
    match = re.search(pattern, content)
    if match:
        insert_pos = match.end()
        str_to_insert = '\n'
        for k, v in pairs.items():
            v_escaped = v.replace("'", "\\'")
            str_to_insert += f"    '{k}': '{v_escaped}',\n"
        content = content[:insert_pos] + str_to_insert + content[insert_pos:]

